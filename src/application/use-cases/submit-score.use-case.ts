import { plausibilityPolicyFor } from '../../domain/score/plausibility-policy';
import {
  InvalidScoreError,
  ScoreClaim,
  type ScoreClaimProps,
} from '../../domain/score/score-claim';
import { ApplicationError } from '../errors/application-error';
import { UNKNOWN_LEVEL_MESSAGE } from '../errors/progress-messages';
import {
  IMPLAUSIBLE_SCORE_MESSAGE,
  SESSION_TAKEN_MESSAGE,
} from '../errors/score-messages';
import type { ILevelRepository } from '../ports/level-repository';
import type {
  IScoreRepository,
  ScoreOutcome,
  StoredSubmission,
} from '../ports/score-repository';

export interface SubmitScoreInput {
  /** The player, already verified by the JWT guard. */
  readonly userId: string;
  /** Generated by the client for each game; makes retries safe. */
  readonly sessionId: string;
  readonly claim: ScoreClaimProps;
}

export interface SubmitScoreResult {
  readonly outcome: ScoreOutcome;
  /** `true` when this `sessionId` had already been accepted. */
  readonly replayed: boolean;
}

/**
 * CU-13: accepts the score of a finished game, or logs it as implausible
 * (RN-39). Retrying the same `sessionId` gives the same answer (CU-13 A4).
 */
export class SubmitScoreUseCase {
  constructor(
    private readonly scores: IScoreRepository,
    private readonly levels: ILevelRepository,
  ) {}

  async execute(input: SubmitScoreInput): Promise<SubmitScoreResult> {
    const stored = await this.scores.findBySession(input.sessionId);
    if (stored) {
      return replay(stored, input.userId);
    }

    const claim = toEntity(input.claim);
    await this.assertLevelExists(claim);

    const reason = plausibilityPolicyFor(claim.gameId).check(claim);
    if (reason !== null) {
      await this.scores.recordRejected(
        input.userId,
        input.sessionId,
        claim,
        reason,
      );
      throw new ApplicationError('unprocessable', IMPLAUSIBLE_SCORE_MESSAGE);
    }

    const outcome = await this.scores.recordAccepted(
      input.userId,
      input.sessionId,
      claim,
    );
    if (outcome) {
      return { outcome, replayed: false };
    }
    // A concurrent request stored this sessionId first: answer like a retry.
    const winner = await this.scores.findBySession(input.sessionId);
    if (!winner) {
      throw new Error(`submission ${input.sessionId} vanished`);
    }
    return replay(winner, input.userId);
  }

  /** In level games, the level must be a published level of that game. */
  private async assertLevelExists(claim: ScoreClaim): Promise<void> {
    if (claim.levelId === null) {
      return;
    }
    const existing = await this.levels.existingIds(claim.gameId, [
      claim.levelId,
    ]);
    if (!existing.has(claim.levelId)) {
      throw new ApplicationError('invalid', UNKNOWN_LEVEL_MESSAGE);
    }
  }
}

/** The answer to a `sessionId` that was already stored. */
function replay(stored: StoredSubmission, userId: string): SubmitScoreResult {
  if (stored.userId !== userId) {
    throw new ApplicationError('invalid', SESSION_TAKEN_MESSAGE);
  }
  if (stored.status === 'rejected') {
    throw new ApplicationError('unprocessable', IMPLAUSIBLE_SCORE_MESSAGE);
  }
  return { outcome: stored.outcome, replayed: true };
}

/** A broken format rule of the entity becomes the contract's `400`. */
function toEntity(props: ScoreClaimProps): ScoreClaim {
  try {
    return ScoreClaim.create(props);
  } catch (error) {
    if (error instanceof InvalidScoreError) {
      throw new ApplicationError('invalid', error.message);
    }
    throw error;
  }
}
